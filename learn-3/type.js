// Primitive type
/*
    1. String
    2. Number
    3. Boolean
    4. Null
    5. Undefined
*/

// 1.String
let name ="siva kalyan";
console.log("My Name is "+name+" HI");
console.log(typeof name);

// 2.Number
let mark = 99;
console.log("Mark is "+mark);
console.log(typeof mark);

// 3. Boolean

let gender = true;
console.log("this best one"+gender);
console.log(typeof gender);

// 4. Null

let test1 = null;
console.log(test1);
console.log(typeof test1);

// 5.  Undefined

let test2 =undefined;
console.log(test2);
console.log(typeof test2);

